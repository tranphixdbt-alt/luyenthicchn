def build(rows, sj, prefix_basis):
    out = []
    for n, (topic, front, back, basis) in enumerate(rows, 1):
        if not basis.startswith(("Giáo trình", "VAS", "VSA")): basis = prefix_basis + basis
        c = {"id": f"{sj}-{n:02d}", "subject": sj, "front": front, "back": back, "basis": basis, "topic": topic}
        assert len(front) <= 160 and len(back) <= 220, (c["id"], len(front), len(back))
        out.append(c)
    assert len(out) == 50 and len({c["front"] for c in out}) == 50
    return out

