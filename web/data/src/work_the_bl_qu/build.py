def make(sj, rows):
    return [{"id": f"{sj}-{i:02d}", "subject": sj, "topic": t, "front": f, "back": b, "basis": s}
            for i, (t, f, b, s) in enumerate(rows, 1)]


topics = collections.defaultdict(set)
for q in json.loads((ROOT / "data" / "questions.json").read_text(encoding="utf-8")):
    topics[q["subject"]].add(q["topic"])

for sj, rows in (("BL", BL), ("QU", QU)):
    cards = make(sj, rows)
    # self-check: same limits as tools/kiem_tra.py
    assert len(cards) == 50, (sj, len(cards))
    assert len({c["front"] for c in cards}) == 50, sj
    for c in cards:
        assert len(c["front"]) <= 160, (c["id"], len(c["front"]))
        assert len(c["back"]) <= 220, (c["id"], len(c["back"]))
        assert c["topic"] in topics[sj], (c["id"], c["topic"])
    (ROOT / "data" / "src" / "the_nho" / f"{sj}.json").write_text(
        json.dumps(cards, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(sj, dict(collections.Counter(c["topic"] for c in cards)))
